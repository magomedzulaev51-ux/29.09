# ЗАМЕЧАНИЕ 5 (стилистическое):
# Функция get_number работает корректно, но сообщение об ошибке
# на английском, тогда как остальной интерфейс на русском.
# Лучше соблюдать единый язык интерфейса.
# ИСПРАВЛЕНИЕ: print("Неверный ввод! Введите число.\n")
# ------------------------------------------------------------
def get_number(prompt):
    """Повторяет запрос до тех пор, пока пользователь не введёт корректное число."""
    while True:
        try:
            return float(input(prompt))
        except ValueError:
            print("Invalid input! Please enter a numeric value.\n")


