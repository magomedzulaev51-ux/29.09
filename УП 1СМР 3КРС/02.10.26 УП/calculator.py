# ЗАМЕЧАНИЕ 6 (критическое):
# В списке valid_ops элемент '' (пустая строка) вместо '*'.
# Из-за этого умножение невозможно выбрать: операция '*' не проходит проверку.
# ИСПРАВЛЕНИЕ: valid_ops = ['+', '-', '*', '/']
#
# ЗАМЕЧАНИЕ 7 (стилистическое):
# В сообщении об ошибке перечислены операции "+, -, *, / или /" —
# повторяющийся слеш, опечатка.
# ИСПРАВЛЕНИЕ: "Недопустимая операция! Выберите +, -, * или /.\n"
# ------------------------------------------------------------
def get_operation():
    """Повторно запрашивает ввод, пока не будет введена допустимая операция."""
    valid_ops = ['+', '-', '', '/']  # ОШИБКА: должно быть '*', а не ''
    while True:
        op = input("Выберите операцию (+, -, *, /): ").strip()
        if op in valid_ops:
            return op
        print("Недопустимая операция! Пожалуйста, выберите +, -, *, / или /.\n")


